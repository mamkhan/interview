-- One row per supply point with the latest version of each meter configuration and usage factor figure.
-- Each figure keeps the date it took effect and the content hash of the sealed file it came from; a
-- message already applied changes nothing, so a redelivery writes the same row. Euf is the estimated and
-- Auf the actual usage factor, in kWh a year, for each of ESB's six usage-factor timeslots.
CREATE TABLE [SupplyPointProfile] (
    [SupplyPointId] varchar(16) NOT NULL,
    [Market] varchar(16) NOT NULL,
    [MeterConfigurationCode] varchar(16) NULL,
    [LoadProfileCode] varchar(8) NULL,
    [DuosGroup] varchar(8) NULL,
    [MeterPointStatusCode] varchar(4) NULL,
    [ConfigurationEffectiveFrom] date NULL,
    [ConfigurationSource] varchar(64) NULL,
    [ConfigurationMessageType] varchar(16) NULL,
    [Euf24H] decimal(20,10) NULL,
    [Euf24HEffectiveFrom] date NULL,
    [Euf24HSource] varchar(64) NULL,
    [Euf00D] decimal(20,10) NULL,
    [Euf00DEffectiveFrom] date NULL,
    [Euf00DSource] varchar(64) NULL,
    [Euf00N] decimal(20,10) NULL,
    [Euf00NEffectiveFrom] date NULL,
    [Euf00NSource] varchar(64) NULL,
    [Euf01D] decimal(20,10) NULL,
    [Euf01DEffectiveFrom] date NULL,
    [Euf01DSource] varchar(64) NULL,
    [Euf01N] decimal(20,10) NULL,
    [Euf01NEffectiveFrom] date NULL,
    [Euf01NSource] varchar(64) NULL,
    [Euf01P] decimal(20,10) NULL,
    [Euf01PEffectiveFrom] date NULL,
    [Euf01PSource] varchar(64) NULL,
    [Auf24H] decimal(20,10) NULL,
    [Auf24HEffectiveFrom] date NULL,
    [Auf24HSource] varchar(64) NULL,
    [Auf00D] decimal(20,10) NULL,
    [Auf00DEffectiveFrom] date NULL,
    [Auf00DSource] varchar(64) NULL,
    [Auf00N] decimal(20,10) NULL,
    [Auf00NEffectiveFrom] date NULL,
    [Auf00NSource] varchar(64) NULL,
    [Auf01D] decimal(20,10) NULL,
    [Auf01DEffectiveFrom] date NULL,
    [Auf01DSource] varchar(64) NULL,
    [Auf01N] decimal(20,10) NULL,
    [Auf01NEffectiveFrom] date NULL,
    [Auf01NSource] varchar(64) NULL,
    [Auf01P] decimal(20,10) NULL,
    [Auf01PEffectiveFrom] date NULL,
    [Auf01PSource] varchar(64) NULL,
    [UpdatedAt] datetimeoffset(3) NOT NULL,
    CONSTRAINT [PK_SupplyPointProfile] PRIMARY KEY ([SupplyPointId])
);
